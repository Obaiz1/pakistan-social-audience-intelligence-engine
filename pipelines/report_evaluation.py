"""Render docs/CLUSTERING_EVALUATION.md and docs/DATA_PROVENANCE.md numbers straight from the built bundle.

    python pipelines/report_evaluation.py [dataset_id]

Numbers in these documents are generated, not typed, so they always match evaluation.json and the bundle tables.
"""

import json
import sys

from common import ROOT  # first: puts backend/ on sys.path

# isort: split
import pandas as pd

from audienceiq.services.datasets import DEMO_ID


def pct(v, d=1):
    return "n/a" if v is None else f"{v * 100:.{d}f}%"


def f3(v):
    return "n/a" if v is None else f"{v:.3f}"


def main() -> None:
    ds_id = sys.argv[1] if len(sys.argv) > 1 else DEMO_ID
    d = ROOT / "data" / "datasets" / ds_id
    meta = json.loads((d / "dataset.json").read_text(encoding="utf-8"))
    ev = json.loads((d / "evaluation.json").read_text(encoding="utf-8"))
    posts = pd.read_csv(d / "posts.csv")
    comments = pd.read_csv(d / "comments.csv")
    profiles = pd.read_csv(d / "cluster_profiles.csv")
    recs = pd.read_csv(d / "recommendations.csv")
    flags = pd.read_csv(d / "anomaly_flags.csv")
    clu = ev["clustering"]
    sel = next(c for c in clu["candidates"] if c["run_id"] == clu["selected_run_id"])
    rec = ev.get("synthetic_recovery") or {}
    audit = ev.get("audit") or {}
    an = ev.get("anomaly_recovery") or {}

    L = ["# Clustering evaluation", "",
         f"_Generated by `pipelines/report_evaluation.py` from `data/datasets/{ds_id}/evaluation.json` "
         f"(dataset built {meta['created_at']}). Do not edit numbers by hand._", "",
         f"**Dataset:** {meta['name']} — {meta['disclaimer']} · {meta['post_count']:,} posts · {meta['comment_count']:,} comments · seed {meta.get('seed')}.", "",
         "## Selected model", "",
         f"- Run `{sel['run_id']}` — **{sel['embedding']} · {sel['algorithm']} {json.dumps(sel['params'])}**",
         f"- Clusters: {sel['n_clusters']} · noise: {pct(sel['noise_rate'])} · cosine silhouette: {f3(sel.get('silhouette_cosine'))} · "
         f"Davies–Bouldin: {f3(sel.get('davies_bouldin'))} · stability (ARI): {f3(sel.get('stability_ari'))} · "
         f"smallest cluster: {pct(sel.get('min_cluster_share'))} · size entropy: {f3(sel.get('size_entropy'))}",
         f"- Selection rule: {json.dumps(clu['selection_rule'])}", "",
         "## All candidates", "",
         "| Representation | Algorithm | Params | k | Noise | Silhouette | DB | Min share | Stability | Eligible | Score | NMI vs synthetic need | Purity | NMI vs language |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in clu["candidates"]:
        p = ",".join(f"{k}={v}" for k, v in c["params"].items() if k != "dims")
        ext = c.get("external", {})
        need = ext.get("synthetic_true_need", {})
        langx = ext.get("language", {})
        mark = " **(selected)**" if c["run_id"] == clu["selected_run_id"] else ""
        L.append(f"| {c['embedding']}{mark} | {c['algorithm']} | {p} | {c['n_clusters']} | {pct(c['noise_rate'], 0)} | "
                 f"{f3(c.get('silhouette_cosine'))} | {f3(c.get('davies_bouldin'))} | {pct(c.get('min_cluster_share'))} | "
                 f"{f3(c.get('stability_ari'))} | {'yes' if c['eligible'] else 'no'} | {f3(c.get('selection_score'))} | "
                 f"{f3(need.get('nmi'))} | {pct(need.get('purity'), 0)} | {f3(langx.get('nmi'))} |")
    L += ["", "Stability is computed only for the four best eligible candidates of the selection family (ADR-007). "
          "Lexical candidates are the baseline (ADR-007a) and are never selected.", "",
          "## Discovered clusters (selected run)", "",
          "| # | Name (post-hoc) | Comments | Share | Name agreement | Cohesion | Top terms | Language mix |",
          "|---|---|---|---|---|---|---|---|"]
    for p in profiles.sort_values("cluster_id").itertuples(index=False):
        langs = json.loads(p.language_mix_json)
        tot = sum(langs.values()) or 1
        lm = ", ".join(f"{k} {v / tot:.0%}" for k, v in list(langs.items())[:3])
        L.append(f"| {p.cluster_id} | {p.label} | {p.size:,} | {p.share:.1%} | {p.label_agreement:.0%} | "
                 f"{'n/a' if pd.isna(p.cohesion) else f'{p.cohesion:.3f}'} | {', '.join(json.loads(p.top_terms_json)[:6])} | {lm} |")
    L += ["", "## Independent multilingual audit", "",
          f"{audit.get('source', 'n/a')}", "",
          f"- Cluster-name accuracy (nearest centre → cluster's post-hoc need vs human label): **{pct(audit.get('cluster_need_accuracy'), 0)}**",
          f"- By language: {', '.join(f'{k} {pct(v, 0)}' for k, v in (audit.get('cluster_need_accuracy_by_language') or {}).items())}",
          f"- By need: {', '.join(f'{k} {pct(v, 0)}' for k, v in (audit.get('cluster_need_accuracy_by_need') or {}).items())}",
          f"- Rule-based reference labeller on the same 100 comments: {pct(audit.get('rule_labeller_accuracy'), 0)}",
          f"- Language ID: {pct(audit.get('langid_accuracy'), 0)} ({', '.join(f'{k} {pct(v, 0)}' for k, v in (audit.get('langid_by_language') or {}).items())})",
          "", "Rows the selected model got wrong (first 15):", "", "| Text | Language | Human need | Cluster need |", "|---|---|---|---|"]
    for e in [x for x in audit.get("examples", []) if not x["hit"]][:15]:
        L.append(f"| {e['text']} | {e['language']} | {e['need']} | {e['cluster_need']} |")
    L += ["", "## Recovery of the synthetic generator's hidden structure (reported only)", "", rec.get("note", ""), "",
          f"- Clusters vs true need: ARI {f3(rec.get('clusters_vs_true_need', {}).get('ari'))}, NMI {f3(rec.get('clusters_vs_true_need', {}).get('nmi'))}, purity {pct(rec.get('clusters_vs_true_need', {}).get('purity'), 0)}",
          f"- Clusters vs true language: NMI {f3(rec.get('clusters_vs_true_language', {}).get('nmi'))} (lower = less language-driven)",
          f"- Rule labeller vs true need: {pct(rec.get('rule_labeller_accuracy_vs_true_need'), 0)} (circular: same author wrote lexicon and templates)",
          f"- Language ID vs true language: {pct(rec.get('langid_accuracy_vs_true_language'), 0)}", "",
          "## Anomaly detection (Q3)", "", an.get("note", ""), "",
          f"- Injected: {an.get('injected')} · flagged posts: {an.get('flagged_posts')} · injected and flagged: {an.get('detected_injected')} · "
          f"recall {pct(an.get('recall'), 0)} · share of flagged posts that were injected {pct(an.get('share_of_flags_that_were_injected'), 0)}",
          f"- By type: {', '.join(f'{k} {v['detected']}/{v['injected']}' for k, v in (an.get('by_type') or {}).items())}",
          f"- Engagement-flag sensitivity: {json.dumps(ev['anomalies'].get('sensitivity_engagement'))}",
          f"- Flags by kind: {json.dumps(ev['anomalies'].get('by_kind'))}; by direction: {json.dumps(ev['anomalies'].get('by_direction'))}",
          f"- Cohort levels used: {json.dumps(ev['anomalies'].get('cohort_levels'))}; unscored (small cohort): {ev['anomalies'].get('posts_unscored_small_cohort')}; immature: {ev['anomalies'].get('posts_immature')}",
          "", "## Limitations", "",
          "- The corpus is synthetic and compositional; real comments are noisier, so real-world agreement will be lower.",
          "- The audit set was written by the same author as the templates and gloss; it is phrased differently but not independent of that author.",
          "- Cluster names come from a keyword reference labeller; ‘Mixed’ clusters are reported as such rather than forced into a need.",
          "- Silhouette on high-dimensional sentence embeddings is low in absolute terms and favours coarse partitions; stability and the audit are reported alongside it.",
          "- Exploratory runs that informed the representation choice are in `docs/evidence/clustering_exploration_*.log` (ADR-007a, ADR-011, ADR-013, ADR-014)."]
    (ROOT / "docs" / "CLUSTERING_EVALUATION.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    plat = posts.groupby("platform").agg(posts=("post_id", "count"), views_missing=("views", lambda s: int(s.isna().sum())),
                                         shares_missing=("shares", lambda s: int(s.isna().sum())))
    P = ["# Data provenance", "",
         f"_Counts generated by `pipelines/report_evaluation.py` from `data/datasets/{ds_id}/` on build {meta['created_at']}._", "",
         "## Datasets in this build", "", "| Dataset | Mode | Posts | Comments | Snapshot | Text | Source | Reuse permission |", "|---|---|---|---|---|---|---|---|",
         f"| `{ds_id}` | {meta['mode']} | {meta['post_count']:,} | {meta['comment_count']:,} | {meta['snapshot_at']} | {meta['text_permission']} | "
         f"{meta['sources'][0]['name']} | {meta['sources'][0]['reuse_permission']} |", "",
         "**No observed data is included in this build.** The YouTube collector (`pipelines/collect_youtube.py`) is implemented but was not run "
         "(the session's permission policy refused using a key from another project; ADR-012). Instagram/TikTok/Facebook data can enter only "
         "through authorised CSV exports.", "",
         f"## Synthetic corpus details (`{ds_id}`)", "",
         f"- Generator: `backend/audienceiq/data/synthetic.py` ({meta.get('generator_version')}), seed {meta.get('seed')}, deterministic (unit-tested).",
         f"- Window: {str(posts['published_at'].min())[:10]} → {str(posts['published_at'].max())[:10]}; snapshot {meta['snapshot_at']}.",
         f"- Brands (fictional): {', '.join(sorted(posts['brand'].unique()))}. Category: {posts['product_category'].iloc[0]}.",
         f"- Platforms: {', '.join(f'{k} {v:,}' for k, v in posts['platform'].value_counts().items())}.",
         f"- Content types: {', '.join(f'{k} {v:,}' for k, v in posts['content_type'].value_counts().items())}.",
         f"- Campaigns: {posts['campaign'].nunique()} ({', '.join(f'{k} {v}' for k, v in posts['campaign'].value_counts().items())}).",
         f"- Comments: {len(comments):,} on {comments['post_id'].nunique():,} posts; detected languages: "
         f"{', '.join(f'{k} {v:,}' for k, v in comments['language_type'].value_counts().items())}.",
         f"- Posts younger than 7 days (excluded from comparisons): {int((posts['days_since_post'] < 7).sum())}.", "",
         "| Platform | Posts | Views not reported | Shares not reported |", "|---|---|---|---|"]
    for k, r in plat.iterrows():
        P.append(f"| {k} | {r['posts']:,} | {r['views_missing']:,} | {r['shares_missing']:,} |")
    P += ["", "Missing views/shares are by design (photos have no views; YouTube reports no shares) and stay null.", "",
          "## Outputs", "",
          f"- Clusters: {len(profiles[profiles['cluster_id'] != -1])}; anomaly flags: {len(flags)} on {flags['post_id'].nunique()} posts; recommendations: {len(recs)}.",
          "- Ground truth for evaluation only: `synthetic_truth_posts.csv` (injected anomalies), `synthetic_truth_comments.csv` (latent need, language).",
          "- Integrity: every file's SHA-256 is listed in `dataset.json` and verified in CI.", "",
          "## Sources checked but not used", "",
          "- 2026 journal article (10,602 observations): no dataset/code availability stated → not used.",
          "- Pakistan's largest e-commerce dataset: transaction records, not comments; no licence shown → not used.",
          "- Pakistani Fashion Catalogue (Hugging Face, 75 rows): licence 'other', casual/menswear retailers → not used.",
          "- Real brand names (Sapphire, Khaadi, Gul Ahmed) appear only in the optional observed-YouTube channel config; synthetic data never uses them."]
    (ROOT / "docs" / "DATA_PROVENANCE.md").write_text("\n".join(P) + "\n", encoding="utf-8")
    print("wrote docs/CLUSTERING_EVALUATION.md and docs/DATA_PROVENANCE.md")


if __name__ == "__main__":
    main()
